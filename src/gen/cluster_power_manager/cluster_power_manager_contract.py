def pack(kind: str, /, **fields: int) -> int:
    layout = LAYOUTS[kind]
    if fields.keys() - dict(layout).keys():
        raise ValueError(f"Unknown {kind} fields")
    value = offset = 0
    for name, width in layout:
        field = fields.get(name, 0)
        if not isinstance(field, int) or not 0 <= field < 1 << width:
            raise ValueError(f"{kind}.{name} does not fit {width} bits")
        value |= field << offset
        offset += width
    return value


def unpack(kind: str, value: int) -> dict[str, int]:
    fields = {}
    for name, width in LAYOUTS[kind]:
        fields[name] = value & ((1 << width) - 1)
        value >>= width
    return fields


def profile(**changes: int) -> dict[str, int]:
    p = DEFAULTS | changes
    group_width = max(1, (p['NUM_CLOCK_GROUPS'] - 1).bit_length())
    isolation_width = max(1, (p['NUM_ISOLATION_GROUPS'] - 1).bit_length())
    p.setdefault('TILE_CLOCK_GROUP_TABLE', sum((t % p['NUM_CLOCK_GROUPS']) << (t * group_width)
                                              for t in range(p['NUM_TILES'])))
    p.setdefault('BOUNDARY_ISOLATION_TABLE', sum((e % p['NUM_ISOLATION_GROUPS']) << (e * isolation_width)
                                              for e in range(p['NUM_BOUNDARY_ENDPOINTS'])))
    return p


def validate(parameters: dict[str, int]) -> dict[str, int]:
    if parameters.keys() - profile().keys():
        raise ValueError('Unknown power parameter')
    p = DEFAULTS | parameters
    for name, (low, high) in BOUNDS.items():
        if not isinstance(p[name], int) or not low <= p[name] <= high:
            raise ValueError(f'{name} must be in [{low}, {high}]')
    for name in BOOLEANS:
        if p[name] not in (0, 1):
            raise ValueError(f'{name} must be Boolean')
    if any(p[name] for name in UNSUPPORTED) or p['POWER_PROFILE'] not in (0, 4):
        raise ValueError('Only Clocked and Protected clocked profiles are implemented')
    if p['POWER_PROFILE'] == 4 and not p['CONTROL_PROTECTION']:
        raise ValueError('Protected profile requires parity or SECDED')
    p = profile(**parameters)
    for name, count, values in [('TILE_CLOCK_GROUP_TABLE', p['NUM_TILES'], p['NUM_CLOCK_GROUPS']),
                                ('BOUNDARY_ISOLATION_TABLE', p['NUM_BOUNDARY_ENDPOINTS'],
                                 p['NUM_ISOLATION_GROUPS'])]:
        width = max(1, (values - 1).bit_length())
        if not 0 <= p[name] < 1 << (count * width) or any(
                (p[name] >> (i * width) & ((1 << width) - 1)) >= values for i in range(count)):
            raise ValueError(f'Invalid {name}')
    return p
