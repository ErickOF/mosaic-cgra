def validate(parameters: dict[str, int]) -> dict[str, int]:
    """Reject unsupported hardware geometries before publishing a platform contract."""
    unknown = parameters.keys() - (profile().keys())
    if unknown:
        raise ValueError(f'Unknown parameters: {unknown}')
    p = DEFAULTS | parameters
    for name, (low, high) in BOUNDS.items():
        if not isinstance(p[name], int) or not low <= p[name] <= high:
            raise ValueError(f'{name} must be in [{low}, {high}]')
    for name in UNSUPPORTED:
        if p[name] != 0:
            raise ValueError(f'{name} is unsupported by runtime v1')
    for name in BOOLEANS:
        if p[name] not in (0, 1):
            raise ValueError(f'{name} must be Boolean')
    p = profile(**parameters)
    if (1 << p['AGE_COUNTER_WIDTH']) - 1 < (p['NUM_PRIORITY_LEVELS'] - 1) * p['AGE_ESCALATION_CYCLES']:
        raise ValueError('Age width cannot represent promotion to maximum rank')
    if p['MAX_ACTIVE_KERNELS'] > min(p['MAX_PENDING_KERNELS'], p['NUM_CLUSTERS']):
        raise ValueError('Active count exceeds available records or clusters')
    if p['MAX_CLUSTERS_PER_KERNEL'] > p['NUM_CLUSTERS']:
        raise ValueError('A kernel cannot request more clusters than the platform')
    if p['RUNTIME_PROFILE'] == 0 and (p['MAX_ACTIVE_KERNELS'] != 1 or p['MAX_PACKAGE_VARIANTS'] != 1):
        raise ValueError('Static requires one active kernel and one precompiled variant')
    table_widths = dict(CLUSTER_PRESENT_MASK=p['NUM_CLUSTERS'],
                        CLUSTER_CAPABILITY_TABLE=p['NUM_CLUSTERS'] * 32,
                        CLUSTER_COMPATIBILITY_TABLE=p['NUM_CLUSTERS'] * 16,
                        CLUSTER_MEMORY_PORT_TABLE=p['NUM_CLUSTERS'] * 16,
                        CLUSTER_SCRATCHPAD_REGION_TABLE=p['NUM_CLUSTERS'] * 32,
                        OWNER_ID_TABLE=p['MAX_OWNERS'] * 16)
    for name, width in table_widths.items():
        if not isinstance(p[name], int) or not 0 <= p[name] < 1 << width:
            raise ValueError(f'{name} must fit its generated table width')
    owners = [p['OWNER_ID_TABLE'] >> (16 * i) & 0xffff for i in range(p['MAX_OWNERS'])]
    if not all(owners) or len(set(owners)) != len(owners):
        raise ValueError('Owner IDs must be nonzero and unique')
    return p
