def profile(**overrides):
    """Derive dependent widths from one source of public parameter truth."""
    p=DEFAULTS | overrides
    p['PREDICATE_WIDTH']=overrides.get('PREDICATE_WIDTH',p['PREDICATE_LANES'])
    p['EVENT_WIDTH']=overrides.get('EVENT_WIDTH',p['EVENT_RECORD_WIDTH'])
    p['CONFIG_WORD_COUNT']=overrides.get('CONFIG_WORD_COUNT',(512+p['MAX_LOOP_DEPTH']*
        (3*p['INDEX_WIDTH']+p['TRIP_COUNT_WIDTH']+5)+63)//64)
    p.setdefault('INPUT_ELASTIC_MASK',(1<<p['DATA_INPUT_PORTS'])-1)
    p.setdefault('OUTPUT_ELASTIC_MASK',(1<<p['DATA_OUTPUT_PORTS'])-1)
    return validate(p)


def validate(p):
    """Reject capabilities without an implemented, verified native composition."""
    fixed=dict(SHELL_DATA_WIDTH=64,CONTROL_WIDTH=32,DATA_METADATA_WIDTH=128,
        CONFIG_DATA_WIDTH=64,EVENT_RECORD_WIDTH=256,EVENT_WIDTH=256,
        DATA_INPUT_PORTS=2,DATA_OUTPUT_PORTS=1,PREDICATE_METADATA_WIDTH=64,
        EVENT_INPUT_PORTS=1,EVENT_OUTPUT_PORTS=1,OWNER_ID_WIDTH=16,KERNEL_ID_WIDTH=16,
        CONTEXT_VERSION_WIDTH=16,STALL_REASON_WIDTH=8,ERROR_CODE_WIDTH=8,
        ASYNC_RESET=0,NUM_EVENT_NAMESPACES=1,SUPPORT_CHECKPOINT=0,
        LINEAR_COUNT_WIDTH=64,LOOP_II_WIDTH=8,BARRIER_GENERATION_WIDTH=4,
        ACTION_TAG_WIDTH=8,EVENT_SEQUENCE_WIDTH=16,TIMEOUT_COUNTER_WIDTH=32,
        SUPPORT_RETENTION=0,SUPPORT_POWER_OFF=0,PREDICATE_PROTECTION=0,CONTROL_PROTECTION=0,
        TILE_ID_WIDTH=16,ARCH_VERSION_WIDTH=16,CAPABILITY_ID_WIDTH=32,
        RUNTIME_TAG_WIDTH=8,TRACE_WIDTH=64,CONTEXT_CHECKSUM_WIDTH=32,
        SUPPORT_CONTEXT_CHECKSUM=1)
    for key,value in fixed.items():
        if p[key]!=value:raise ValueError(f'{key} requires {value}')
    ranges=dict(TILE_ID=(0,p['MAX_EVENT_SOURCES']-1),CONFIG_QUEUE_DEPTH=(2,16),PREDICATE_LANES=(1,16),PREDICATE_DEPTH=(2,16),
        PREDICATE_INPUT_PORTS=(1,2),PREDICATE_OUTPUT_PORTS=(1,4),CONTEXT_DEPTH=(1,16),
        CONTROL_REGISTER_DEPTH=(4,16),FU_PROFILE=(0,1),MAX_LOOP_DEPTH=(1,4),
        INDEX_WIDTH=(4,32),TRIP_COUNT_WIDTH=(2,32),NUM_EVENTS=(1,16),
        EVENT_COUNT_WIDTH=(1,8),MAX_EVENT_SOURCES=(1,16),NUM_WAIT_SLOTS=(1,4),
        NUM_BARRIERS=(1,4),MAX_PARTICIPANTS=(1,16),MAX_OUTSTANDING_ACTIONS=(1,8),
        ACTION_QUEUE_DEPTH=(p['MAX_OUTSTANDING_ACTIONS'],16),
        ACTION_RESPONSE_DEPTH=(p['MAX_OUTSTANDING_ACTIONS'],16),MAX_PRIORITY_BURST=(1,16),
        LOOP_EXPORT_LEVELS=(1,p['MAX_LOOP_DEPTH']),INPUT_BUFFER_DEPTH=(1,4),
        OUTPUT_BUFFER_DEPTH=(1,4),EVENT_INPUT_FIFO_DEPTH=(1,16),
        EVENT_OUTPUT_FIFO_DEPTH=(1,16),WAIT_RESULT_QUEUE_DEPTH=(1,16),
        BARRIER_RELEASE_QUEUE_DEPTH=(1,16),CONTROL_PROTECTION=(0,2),
        CONTEXT_PROTECTION=(0,2),EVENT_PROTECTION=(0,1))
    for key,(low,high) in ranges.items():
        if not isinstance(p[key],int) or not low<=p[key]<=high:
            raise ValueError(f'{key} outside {low}..{high}')
    for key in ('SUPPORT_CONTEXT_COORDINATION','SUPPORT_CLUSTER_LIFECYCLE',
                'SUPPORT_TIMEOUT','SUPPORT_PREDICATED_TOKEN','REQUIRE_CANONICAL_FORMAT',
                'CONFIG_ASYNC','SUPPORT_TRACE'):
        if p[key] not in (0,1):raise ValueError(f'{key} must be Boolean')
    if not p['FU_PROFILE'] and any(p[k] for k in ('SUPPORT_CONTEXT_COORDINATION',
            'SUPPORT_CLUSTER_LIFECYCLE','SUPPORT_TIMEOUT')):
        raise ValueError('CPT-Local excludes cluster coordination and timeouts')
    expected=(512+p['MAX_LOOP_DEPTH']*(3*p['INDEX_WIDTH']+p['TRIP_COUNT_WIDTH']+5)+63)//64
    if p['CONFIG_WORD_COUNT']!=expected:raise ValueError('Incomplete context geometry')
    if p['PREDICATE_WIDTH']!=p['PREDICATE_LANES']:raise ValueError('Predicate lane mismatch')
    if p['CONFIG_ASYNC'] and p['CONFIG_QUEUE_DEPTH'] & (p['CONFIG_QUEUE_DEPTH']-1):
        raise ValueError('Asynchronous configuration queue requires a power of two')
    if p.get('INPUT_ELASTIC_MASK',3)!=3 or p.get('OUTPUT_ELASTIC_MASK',1)!=1:
        raise ValueError('CPT uses elastic shell channels')
    return p


