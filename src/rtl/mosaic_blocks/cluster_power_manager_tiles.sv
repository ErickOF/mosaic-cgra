`timescale 1ns / 1ps
// One released always-on tile controller per generated power region. The parent
// owns the shared rail, root clock and boundary; children only reach RUN/IDLE.
module cluster_power_manager_tiles #(
    parameter int TILES = 16,
    parameter int GROUPS = 8,
    parameter int STALLS = 8,
    parameter int TIMEOUT = 4095,
    localparam int TG = GROUPS > 1 ? $clog2(GROUPS) : 1,
    parameter [TILES*TG-1:0] TILE_GROUPS = '0
) (
    input wire i_clk,
    input wire i_rstb,
    input wire i_status_enable,
    input wire i_power_good,
    input wire [7:0] i_epoch,
    input wire [TILES-1:0] i_config_valid,
    input wire [TILES-1:0] i_command_valid,
    input wire [2:0] i_command,
    input wire [TILES-1:0] i_busy,
    input wire [TILES-1:0] i_quiescent,
    input wire [TILES-1:0] i_drain_done,
    input wire [TILES*STALLS-1:0] i_stalls,
    input wire [GROUPS-1:0] i_groups,
    output wire [TILES-1:0] o_configured,
    output wire [TILES-1:0] o_config_ready,
    output wire [TILES-1:0] o_config_accepted,
    output wire [TILES-1:0] o_command_ready,
    output wire [TILES-1:0] o_command_done,
    output wire [TILES-1:0] o_command_rejected,
    output wire [TILES*4-1:0] o_state,
    output wire [TILES-1:0] o_clock,
    output wire [TILES-1:0] o_groups,
    output wire [TILES-1:0] o_error
);
    for (genvar t = 0; t < TILES; t++) begin : g_tile
        localparam int GROUP = int'(TILE_GROUPS[t*TG+:TG]);

        tile_power_controller #(
            .NUM_CLOCK_GROUPS(1),
            .NUM_WAKE_SOURCES(1),
            .NUM_STALL_REASONS(STALLS),
            .IDLE_ENTRY_CYCLES(1),
            .MIN_IDLE_RESIDENCY_CYCLES(1),
            .WAKEUP_STABILIZE_CYCLES(1),
            .ISOLATION_SETUP_CYCLES(1),
            .POWER_STABLE_CYCLES(1),
            .RESET_HOLD_CYCLES(1),
            .DRAIN_TIMEOUT_CYCLES(TIMEOUT),
            .ACK_TIMEOUT_CYCLES(TIMEOUT),
            .POWER_TIMEOUT_CYCLES(TIMEOUT),
            .WAKE_ON_EVENT(0),
            .CLOCK_GROUP_ALWAYS_ON_MASK(1'b0),
            .WAKEUP_CLOCK_GROUP_MASK(1'b1)
        ) u_tile (
            .i_aon_clk(i_clk),
            .i_aon_rstb(i_rstb),
            .i_error_clear(1'b0),
            .i_test_mode(1'b0),
            .i_test_clock_enable(1'b0),
            .i_config_valid(i_config_valid[t]),
            .o_config_ready(o_config_ready[t]),
            .i_config_auto_idle_enable(1'b0),
            .i_config_wake_enable(1'b0),
            .i_config_context_check(1'b1),
            .i_config_context_id(i_epoch),
            .o_config_accepted(o_config_accepted[t]),
            .o_config_rejected(),
            .i_command_valid(i_command_valid[t]),
            .o_command_ready(o_command_ready[t]),
            .i_command(i_command),
            .i_command_context_id(i_epoch),
            .o_command_accepted(),
            .o_command_rejected(o_command_rejected[t]),
            .o_command_done(o_command_done[t]),
            .i_tile_busy(i_status_enable ? i_busy[t] : 1'b0),
            .i_tile_quiescent(i_status_enable ? i_quiescent[t] : 1'b1),
            .i_drain_done(i_status_enable ? i_drain_done[t] : 1'b1),
            .i_stall_reason(i_status_enable ? i_stalls[t*STALLS+:STALLS] : {STALLS{1'b0}}),
            .i_clock_group_request(i_status_enable ? i_groups[GROUP] : 1'b1),
            .i_wakeup_event(1'b0),
            .i_power_good_async(i_power_good),
            .i_retention_save_ack(1'b0),
            .i_retention_restore_ack(1'b0),
            .o_tile_accept_enable(),
            .o_drain_request(),
            .o_tile_clock_enable(o_clock[t]),
            .o_clock_group_enable(o_groups[t]),
            .o_operand_isolation_enable(),
            .o_write_disable(),
            .o_tile_reset_request(),
            .o_isolation_enable(),
            .o_retention_save(),
            .o_retention_restore(),
            .o_power_switch_enable(),
            .o_power_state(o_state[t*4+:4]),
            .o_target_state(),
            .o_previous_stable_state(),
            .o_transition_active(),
            .o_power_good_sync(),
            .o_wakeup_pending(),
            .o_policy_valid(o_configured[t]),
            .o_active_context_id(),
            .o_idle_count(),
            .o_state_residency(),
            .o_idle(),
            .o_quiescent(),
            .o_error(),
            .o_fatal_error(o_error[t]),
            .o_error_code(),
            .o_event_state_change(),
            .o_event_idle_entry(),
            .o_event_wakeup(),
            .o_event_stall_entry(),
            .o_event_retention_entry(),
            .o_event_off_entry(),
            .o_event_timeout()
        );
    end
endmodule
