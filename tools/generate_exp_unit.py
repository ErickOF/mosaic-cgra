"""Generate and certify the immutable exp-unit endpoint/constant family.

MPFR directed bounds at 512 bits certify nearest-even integer rounding. The
128-fraction-bit master is additionally checked against direct bounds for every
supported 1..64 fraction width, eliminating double-rounding ambiguity.
"""
import argparse
import hashlib
import json
from pathlib import Path
import gmpy2 as g

ROOT = Path(__file__).resolve().parents[1]
BITS = 128
PRECISION = 512
ADDRESS = 8
MAX_FRACTION = 64


def nearest(numerator, denominator):
    quotient, remainder = divmod(int(numerator), int(denominator))
    return quotient + int(2 * remainder > denominator or
                          2 * remainder == denominator and quotient % 2 == 1)


def integer(value, fraction):
    n, d = value.as_integer_ratio()
    return nearest(int(n) << fraction, d)


def bounds(index=None):
    if index is not None:
        with g.context(precision=PRECISION, round=g.RoundDown):
            lower = g.exp2(g.mpfr(index) / (1 << ADDRESS))
        with g.context(precision=PRECISION, round=g.RoundUp):
            upper = g.exp2(g.mpfr(index) / (1 << ADDRESS))
    else:
        with g.context(precision=PRECISION, round=g.RoundDown):
            low_ln2 = g.log(g.mpfr(2))
        with g.context(precision=PRECISION, round=g.RoundUp):
            high_ln2 = g.log(g.mpfr(2))
            upper = g.mpfr(1) / low_ln2
        with g.context(precision=PRECISION, round=g.RoundDown):
            lower = g.mpfr(1) / high_ln2
    return lower, upper


def certified(pair, fraction):
    low, high = (integer(value, fraction) for value in pair)
    if low != high:
        raise ArithmeticError('Insufficient precision to certify the rounded integer')
    return low


def generate():
    if g.version() != '2.2.1' or g.mpfr_version() != 'MPFR 4.2.1':
        raise RuntimeError('Generation requires gmpy2 2.2.1 and MPFR 4.2.1')
    pairs = [bounds(i) for i in range((1 << ADDRESS) + 1)]
    entries = [certified(pair, BITS) for pair in pairs]
    constant_bounds = bounds()
    constant = certified(constant_bounds, BITS)
    for pair, master in zip([*pairs, constant_bounds], [*entries, constant], strict=True):
        for fraction in range(1, MAX_FRACTION + 1):
            derived = nearest(master, 1 << (BITS - fraction))
            assert derived == certified(pair, fraction), 'Double rounding in master family'
    payload = b''.join(value.to_bytes(17, 'little') for value in entries)
    metadata = dict(schema_version=1, generator='tools/generate_exp_unit.py',
        gmpy2=g.version(), mpfr=g.mpfr_version(), gmp=g.mp_version(),
        precision_bits=PRECISION, master_fraction_bits=BITS,
        maximum_address_width=ADDRESS, maximum_fraction_width=MAX_FRACTION,
        rounding='nearest_ties_even; certified MPFR lower/upper interval agreement',
        endpoint_definition='round_even(2**(i/256) * 2**128)',
        constant_definition='round_even((1/log(2)) * 2**128)',
        endpoint_sha256=hashlib.sha256(payload).hexdigest(),
        constant_sha256=hashlib.sha256(constant.to_bytes(17, 'little')).hexdigest(),
        log2e_constant=f'{constant:033x}', endpoints=[f'{value:033x}' for value in entries],
        certification=dict(all_direct_fraction_widths=list(range(1, MAX_FRACTION + 1)),
                           endpoint_count=len(entries), directed_interval_rounding='PASS'))
    source = '''`timescale 1ns / 1ps

// Generated by tools/generate_exp_unit.py. Do not edit by hand.
// MPFR-directed interval certification and hashes accompany the JSON image.
package exp_unit_tables_pkg;
    localparam int MASTER_FRACTION = 128;
    localparam int MAX_FRACTION = 64;
    localparam int MAX_ADDRESS = 8;
    localparam logic [129:0] LOG2E_MASTER = 130'hCONSTANT;

    function automatic logic [129:0] endpoint(input int unsigned index);
        case (index)
'''.replace('CONSTANT', f'{constant:033x}')
    source += ''.join(f"            {i}: endpoint = 130'h{value:033x};\n" for i, value in enumerate(entries))
    source += '''            default: endpoint = '0;
        endcase
    endfunction

    function automatic logic [129:0] round_master(
        input logic [129:0] value,
        input int fraction
    );
        logic [129:0] quotient;
        logic [129:0] remainder;
        logic [129:0] half;
        quotient = value >> (MASTER_FRACTION - fraction);
        half = 130'd1 << (MASTER_FRACTION - fraction - 1);
        remainder = value & ((half << 1) - 1'b1);
        return quotient + 130'(remainder > half || (remainder == half && quotient[0]));
    endfunction

    function automatic logic [129:0] table_value(
        input int index,
        input int address_width,
        input int fraction
    );
        return round_master(endpoint(index << (MAX_ADDRESS - address_width)), fraction);
    endfunction

    // Reflected CRC-32/ISO-HDLC, little-endian zero-padded bytes per table word.
    function automatic logic [31:0] crc_byte(
        input logic [31:0] crc,
        input logic [7:0] value
    );
        logic [31:0] next_crc;
        next_crc = crc ^ {24'b0, value};
        for (int bit_index = 0; bit_index < 8; bit_index++)
            next_crc = next_crc[0] ? (next_crc >> 1) ^ 32'hedb88320 : next_crc >> 1;
        return next_crc;
    endfunction

    function automatic logic [31:0] table_crc(
        input int address_width,
        input int fraction,
        input int width
    );
        logic [31:0] crc;
        logic [255:0] value;
        logic [129:0] generated_value;
        logic [129:0] quotient;
        logic [129:0] half;
        logic [129:0] remainder;
        crc = '1;
        for (int index = 0; index <= (1 << address_width); index++) begin
            generated_value = endpoint(index << (MAX_ADDRESS - address_width));
            quotient = generated_value >> (MASTER_FRACTION - fraction);
            half = 130'd1 << (MASTER_FRACTION - fraction - 1);
            remainder = generated_value & ((half << 1) - 1'b1);
            value = 256'(quotient) + 256'(remainder > half ||
                (remainder == half && quotient[0]));
            for (int byte_index = 0; byte_index < (width + 7) / 8; byte_index++)
            begin
                crc = crc ^ {24'b0, value[byte_index*8+:8]};
                for (int bit_index = 0; bit_index < 8; bit_index++)
                    crc = crc[0] ? (crc >> 1) ^ 32'hedb88320 : crc >> 1;
            end
        end
        return ~ crc;
    endfunction

    function automatic logic [31:0] constant_crc(input int fraction);
        logic [31:0] crc;
        logic [129:0] value;
        crc = '1;
        value = round_master(LOG2E_MASTER, fraction);
        for (int byte_index = 0; byte_index < (fraction + 9) / 8; byte_index++)
        begin
            crc = crc ^ {24'b0, 8'(value >> (8 * byte_index))};
            for (int bit_index = 0; bit_index < 8; bit_index++)
                crc = crc[0] ? (crc >> 1) ^ 32'hedb88320 : crc >> 1;
        end
        return ~ crc;
    endfunction
endpackage
'''
    # Icarus 12 rejects a package constant function calling a case-based package
    # function with a loop variable. Inline the same certified literals here.
    crc_case = 'case (index << (MAX_ADDRESS - address_width))\n'
    crc_case += ''.join(f"                {i}: generated_value = 130'h{value:033x};\n"
                        for i, value in enumerate(entries))
    crc_case += "                default: generated_value = '0;\n            endcase"
    source = source.replace('generated_value = endpoint(index << (MAX_ADDRESS - address_width));', crc_case)
    return source, json.dumps(metadata, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    directory = ROOT / 'src/rtl/building_blocks/generated'
    for name, content in zip(('exp_unit_tables_pkg.sv', 'exp_unit_tables.json'), generate(), strict=True):
        path = directory / name
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Generated artifact differs: {path}')
        else:
            path.write_text(content, encoding='utf-8')
    print('Exp-unit generated table and log2(e) certification PASS')


if __name__ == '__main__':
    main()
